/* test_gif.c — the animated GIF decoder + player + Picture widget
 * tests (1.1.0 / C-4).
 *
 * Three fixtures:
 *   - matrix.gif (PIL-generated, REAL encoder output: compressed
 *     LZW with table growth, per-frame transparency, the disposal
 *     matrix 1/2/3, a NETSCAPE loop) — the interop proof;
 *   - interlaced.gif (hand-written): the four-pass row order — the
 *     de-interlace pin;
 *   - delays.gif (hand-written): exact delay values incl. the
 *     compatibility floor, the NETSCAPE loop count.
 *
 * The player runs headless on plain offscreen surfaces; the Picture
 * widget's TIMER half needs a context — driven here through a real
 * X11 window when DISPLAY exists (honest skip otherwise), asserting
 * that the pixels CHANGE over time without any app-side redraw.
 */

#include "hermetic_env.h"
#include "fdk/fdk.h"
#include "fdk/fdk_surface.h"
#include "fdk/fdk_widgets.h"

#include <assert.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>

/* The fixtures (generated by scripts in the project's test-data
 * pipeline; embedded so the suite is hermetic). */
#include "test_gif_fixtures.h"

static fdk_u32 px_at(fdk_surface *s, int x, int y) {
    fdk_surface_info info;
    assert(fdk_ok(fdk_surface_get_info(s, &info)));
    return info.pixels[(size_t)y * (size_t)info.stride + (size_t)x];
}

static void assert_rgb(fdk_surface *s, int x, int y, int r, int g,
                       int b, const char *what) {
    fdk_u32 px = px_at(s, x, y);
    int pr = (int)((px >> 16) & 0xFFu);
    int pg = (int)((px >> 8) & 0xFFu);
    int pb = (int)(px & 0xFFu);
    if (pr != r || pg != g || pb != b) {
        fprintf(stderr,
                "FAIL %s at (%d,%d): got %02X%02X%02X want %02X%02X%02X\n",
                what, x, y, pr, pg, pb, r, g, b);
        assert(false && "pixel mismatch");
    }
}

static void assert_transparent(fdk_surface *s, int x, int y,
                               const char *what) {
    fdk_u32 px = px_at(s, x, y);
    if ((px >> 24) != 0) {
        fprintf(stderr, "FAIL %s at (%d,%d): alpha %u\n", what, x, y,
                (unsigned)(px >> 24));
        assert(false && "expected transparent");
    }
}

static void assert_rgb_u32(fdk_surface *s, int x, int y, fdk_u32 want) {
    fdk_u32 got = px_at(s, x, y);
    if (got != want) {
        fprintf(stderr, "FAIL u32 pin at (%d,%d): got %08X want %08X\n",
                x, y, got, want);
        assert(false && "u32 mismatch");
    }
}

/* ---- the loader ---- */

static void test_load_errors(void) {
    fdk_gif *g = NULL;
    assert(fdk_gif_load_bytes(NULL, 10, &g) ==
           FDK_ERR_INVALID_ARGUMENT);
    assert(fdk_gif_load_bytes("GIF89a", 6, &g) ==
           FDK_ERR_UNSUPPORTED); /* truncated header */
    assert(fdk_gif_load_bytes("PNG....", 8, &g) ==
           FDK_ERR_UNSUPPORTED);
    /* Not a GIF at all. */
    fdk_u8 junk[64];
    memset(junk, 0xAB, sizeof(junk));
    assert(fdk_gif_load_bytes(junk, sizeof(junk), &g) ==
           FDK_ERR_UNSUPPORTED);
    assert(fdk_gif_load("/nonexistent/path.gif", &g) ==
           FDK_ERR_NOT_FOUND);
    printf("[ok] gif load: argument + signature + path errors\n");
}

/* ---- the disposal matrix (the PIL interop fixture) ---- */

static void test_disposal_matrix(void) {
    fdk_gif *gif = NULL;
    assert(fdk_ok(fdk_gif_load_bytes(matrix_gif, MATRIX_GIF_LEN,
                                      &gif)));
    assert(fdk_gif_frame_count(gif) == 5);
    fdk_i32 w = 0, h = 0;
    fdk_gif_canvas_size(gif, &w, &h);
    assert(w == 8 && h == 8);
    assert(fdk_gif_loop_count(gif) == 0); /* loop forever */

    fdk_surface *canvas = NULL;
    assert(fdk_ok(fdk_surface_create_format(w, h,
                                            FDK_SURFACE_FORMAT_ARGB8888,
                                            &canvas)));
    fdk_gif_player *p = fdk_gif_player_create(gif, canvas);
    assert(p != NULL);
    assert(fdk_gif_player_frame(p) == UINT32_MAX);

    /* Frame 0: full red (PIL reindexed the palette — take the
     * painted color as the reference and pin everything relative
     * to it). */
    assert(fdk_gif_player_next(p) == 0);
    fdk_u32 c0 = px_at(canvas, 0, 0);
    fdk_u32 c_center = px_at(canvas, 3, 3);
    assert(c0 == c_center && (c0 >> 24) == 0xFF); /* uniform, opaque */

    /* Frame 1: a 4x4 block of a DIFFERENT color at the center. */
    assert(fdk_gif_player_next(p) == 1);
    fdk_u32 block = px_at(canvas, 3, 3);
    assert(block != c0 && (block >> 24) == 0xFF);
    assert(px_at(canvas, 0, 0) == c0); /* untouched ring */

    /* Frame 2: fully transparent frame over a disposal-2 (clear)
     * previous frame: the center must read TRANSPARENT (the
     * interoperable restore-to-background), the ring keeps c0. */
    assert(fdk_gif_player_next(p) == 2);
    assert_transparent(canvas, 3, 3, "disposal-2 clear");
    assert_transparent(canvas, 5, 5, "disposal-2 clear (corner)");
    assert_rgb_u32(canvas, 0, 0, c0);

    /* Frame 3: full blue (disposal 3 on the way out). */
    assert(fdk_gif_player_next(p) == 3);
    fdk_u32 c3 = px_at(canvas, 0, 0);
    assert(c3 != c0 && (c3 >> 24) == 0xFF);
    assert(px_at(canvas, 3, 3) == c3);

    /* Frame 4: transparent frame after a disposal-3: the canvas
     * restores to the frame-2 state (transparent center, c0 ring). */
    assert(fdk_gif_player_next(p) == 4);
    assert_transparent(canvas, 3, 3, "disposal-3 restore");
    assert_rgb_u32(canvas, 0, 0, c0);

    /* Looping: next wraps to frame 0. */
    assert(fdk_gif_player_next(p) == 0);
    assert(px_at(canvas, 3, 3) == c0); /* uniform red again */

    /* Reset: transparent + nothing drawn. */
    fdk_gif_player_reset(p);
    assert(fdk_gif_player_frame(p) == UINT32_MAX);
    assert_transparent(canvas, 0, 0, "reset clears");
    assert(fdk_gif_player_next(p) == 0);
    assert(px_at(canvas, 3, 3) == c0);

    fdk_gif_player_destroy(p);
    fdk_surface_destroy(canvas);
    fdk_gif_destroy(gif);
    printf("[ok] gif disposal matrix: keep / clear-to-transparent / "
           "restore-to-previous, loop wrap, reset\n");
}

/* ---- the interlace pin ---- */

static void test_interlace(void) {
    fdk_gif *gif = NULL;
    assert(fdk_ok(fdk_gif_load_bytes(interlaced_gif,
                                      INTERLACED_GIF_LEN, &gif)));
    assert(fdk_gif_frame_count(gif) == 1);
    fdk_surface *canvas = NULL;
    assert(fdk_ok(fdk_surface_create_format(
        8, 8, FDK_SURFACE_FORMAT_ARGB8888, &canvas)));
    fdk_gif_player *p = fdk_gif_player_create(gif, canvas);
    assert(p != NULL);
    assert(fdk_gif_player_next(p) == 0);

    /* Row bands: rows 0-1 red, 2-3 green, 4-5 blue, 6-7 red. A
     * missing de-interlace would scramble exactly this. */
    for (int y = 0; y < 8; y++) {
        int want = (y / 2) % 3;
        int r = (want == 0) ? 255 : 0;
        int g = (want == 1) ? 255 : 0;
        int b = (want == 2) ? 255 : 0;
        for (int x = 0; x < 8; x += 3) {
            assert_rgb(canvas, x, y, r, g, b, "interlace band");
        }
    }
    fdk_gif_player_destroy(p);
    fdk_surface_destroy(canvas);
    fdk_gif_destroy(gif);
    printf("[ok] gif interlace: four-pass row order de-interlaced\n");
}

/* ---- the delay + loop pins ---- */

static void test_delays_and_loop(void) {
    fdk_gif *gif = NULL;
    assert(fdk_ok(fdk_gif_load_bytes(delays_gif, DELAYS_GIF_LEN, &gif)));
    assert(fdk_gif_frame_count(gif) == 3);
    assert(fdk_gif_loop_count(gif) == 3); /* NETSCAPE */
    /* 0cs -> floor 100; 1cs (10ms) -> floor 100; 2cs -> 20. */
    assert(fdk_gif_frame_delay_ms(gif, 0) == 100);
    assert(fdk_gif_frame_delay_ms(gif, 1) == 100);
    assert(fdk_gif_frame_delay_ms(gif, 2) == 20);
    /* Out-of-range reads 0. */
    assert(fdk_gif_frame_delay_ms(gif, 3) == 0);

    fdk_surface *canvas = NULL;
    assert(fdk_ok(fdk_surface_create_format(
        4, 4, FDK_SURFACE_FORMAT_ARGB8888, &canvas)));
    fdk_gif_player *p = fdk_gif_player_create(gif, canvas);
    assert(p != NULL);
    /* Player contract violations: NULL, wrong size, wrong format. */
    assert(fdk_gif_player_create(NULL, canvas) == NULL);
    assert(fdk_gif_player_create(gif, NULL) == NULL);
    fdk_surface *rgb = NULL;
    assert(fdk_ok(fdk_surface_create(4, 4, &rgb))); /* XRGB8888 */
    assert(fdk_gif_player_create(gif, rgb) == NULL);
    fdk_surface *big = NULL;
    assert(fdk_ok(fdk_surface_create_format(
        5, 4, FDK_SURFACE_FORMAT_ARGB8888, &big)));
    assert(fdk_gif_player_create(gif, big) == NULL);
    fdk_surface_destroy(rgb);
    fdk_surface_destroy(big);

    /* The three frames paint their colors. */
    assert(fdk_gif_player_next(p) == 0);
    assert_rgb(canvas, 0, 0, 255, 0, 0, "frame 0 red");
    assert(fdk_gif_player_next(p) == 1);
    assert_rgb(canvas, 0, 0, 0, 255, 0, "frame 1 green");
    assert(fdk_gif_player_next(p) == 2);
    assert_rgb(canvas, 0, 0, 0, 0, 255, "frame 2 blue");

    fdk_gif_player_destroy(p);
    fdk_surface_destroy(canvas);
    fdk_gif_destroy(gif);
    printf("[ok] gif delays: the compatibility floor + exact values, "
           "NETSCAPE loop, player surface contract\n");
}

/* ---- the single-frame GIF + the file path ---- */

static void test_single_frame_file(void) {
    /* Write the fixture to a temp file: the path loader leg. */
    char path[] = "/tmp/fdk-gif-test-XXXXXX";
    int fd = mkstemp(path);
    assert(fd >= 0);
    FILE *f = fdopen(fd, "wb");
    assert(f != NULL);
    assert(fwrite(single_gif, 1, SINGLE_GIF_LEN, f) == SINGLE_GIF_LEN);
    fclose(f);

    fdk_gif *gif = NULL;
    assert(fdk_ok(fdk_gif_load(path, &gif)));
    assert(fdk_gif_frame_count(gif) == 1);
    fdk_i32 w = 0, h = 0;
    fdk_gif_canvas_size(gif, &w, &h);
    assert(w == 4 && h == 4);

    fdk_surface *canvas = NULL;
    assert(fdk_ok(fdk_surface_create_format(
        w, h, FDK_SURFACE_FORMAT_ARGB8888, &canvas)));
    fdk_gif_player *p = fdk_gif_player_create(gif, canvas);
    assert(p != NULL);
    assert(fdk_gif_player_next(p) == 0);
    assert_rgb(canvas, 1, 1, 255, 255, 0, "single-frame yellow");
    /* Looping a single frame just redraws it. */
    assert(fdk_gif_player_next(p) == 0);
    assert_rgb(canvas, 1, 1, 255, 255, 0, "single-frame yellow again");

    fdk_gif_player_destroy(p);
    fdk_surface_destroy(canvas);
    fdk_gif_destroy(gif);
    remove(path);
    printf("[ok] gif file path: single-frame load + composite\n");
}

/* ---- the Picture widget, headless half ----
 *
 * A detached tree (no window, no context): the animation LOADS and
 * composites frame 0, but no clock exists to start — the Spinner's
 * honesty rule. The timer-driven repaint half lives in the X11 GUI
 * suite (test_x11_integration.c), where a real window and real
 * readback exist. */

static void test_picture_animated(void) {
    char path[] = "/tmp/fdk-gif-pic-XXXXXX";
    int fd = mkstemp(path);
    assert(fd >= 0);
    FILE *f = fdopen(fd, "wb");
    assert(f != NULL);
    assert(fwrite(matrix_gif, 1, MATRIX_GIF_LEN, f) == MATRIX_GIF_LEN);
    fclose(f);

    fdk_widget *root = NULL;
    assert(fdk_ok(fdk_widget_create(NULL, NULL,
                                    (fdk_rect){0, 0, 80, 80}, &root)));
    fdk_widget *pic = NULL;
    assert(fdk_ok(fdk_picture_create(root, &pic)));
    fdk_widget_arrange(pic, (fdk_rect){4, 4, 64, 64});
    assert(fdk_ok(fdk_picture_set_animated_file(pic, path)));
    assert(fdk_picture_is_animated(pic));
    assert(!fdk_picture_get_playing(pic)); /* detached: no clock */
    assert(fdk_picture_image_width(pic) == 8);
    assert(fdk_picture_image_height(pic) == 8);

    /* The painted tree shows frame 0 (uniform) scaled into the
     * arranged rect (CONTAIN: 64x64 from 8x8 = 8x upscale). The
     * offscreen tree surface is XRGB8888 — the alpha channel lives
     * in the picture's OWN canvas, not here. */
    fdk_surface *s = NULL;
    assert(fdk_ok(fdk_surface_create(80, 80, &s)));
    fdk_widget_invalidate_all(root);
    fdk_widget_tree_paint(root, s);
    fdk_u32 a = px_at(s, 20, 20);
    fdk_u32 b = px_at(s, 50, 50);
    assert(a == b && a != 0);
    /* Outside the picture: untouched (0). */
    assert(px_at(s, 2, 2) == 0);

    /* A static set drops the animation. */
    assert(fdk_ok(fdk_picture_set_from_file(pic, path)));
    assert(!fdk_picture_is_animated(pic));
    assert(!fdk_picture_get_playing(pic));

    /* Destroying an animated picture (ASan: the gif, player, canvas,
     * and the absent timer all released). */
    assert(fdk_ok(fdk_picture_set_animated_file(pic, path)));
    fdk_widget_destroy(pic);
    fdk_widget_destroy(root);
    fdk_surface_destroy(s);
    remove(path);
    printf("[ok] picture animated (headless): frame-0 canvas, the "
           "detached-tree no-clock rule, static drop, clean destroy\n");
}

int main(void) {
    test_load_errors();
    test_disposal_matrix();
    test_interlace();
    test_delays_and_loop();
    test_single_frame_file();
    test_picture_animated();
    printf("all gif tests passed\n");
    return 0;
}
