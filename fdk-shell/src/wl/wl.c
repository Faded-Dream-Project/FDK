/* ---- per-shell state ------------------------------------------------------ */

typedef struct wl_output_rec {
    struct wl_output *output; /* bound proxy (role teardown at shutdown) */
    uint32_t global_name;     /* registry name (the retirement key)  */
    char name[64];            /* connector name, wl_output v4        */
    int gone;                 /* global removed (kept for stability) */
} wl_output_rec;

typedef struct wl_shell_state {
    struct wl_display *display; /* borrowed: FDK's connection       */
    struct wl_registry *registry; /* fdk-shell's OWN registry        */
    struct zwlr_layer_shell_v1 *shell; /* NULL when unsupported     */
    struct wl_compositor *compositor;
    wl_output_rec *outputs;
    size_t output_count;
    size_t output_capacity;
} wl_shell_state;

/* ---- per-layer state ------------------------------------------------------ */

typedef struct wl_layer_state {
    struct zwlr_layer_surface_v1 *ls; /* the ROLE (add-on owned)    */
    struct wl_output *output;         /* NULL = every output        */
    int closed;
} wl_layer_state;

/* ---- registry + outputs ---------------------------------------------------- */

static void wl_output_name_cb(void *data, struct wl_output *output,
                              const char *name) {
    (void)output;
    wl_output_rec *rec = data;
    snprintf(rec->name, sizeof(rec->name), "%s", name != NULL ? name : "");
}

/* Typed no-ops for the v4 events fdk-shell does not consume (the
 * listener struct wants every member; leaving one NULL aborts the
 * connection when the event arrives — libwayland's rule). */
static void wl_output_geometry_cb(void *data, struct wl_output *output,
                                  int32_t x, int32_t y, int32_t pw,
                                  int32_t ph, int32_t subpixel,
                                  const char *make, const char *model,
                                  int32_t transform) {
    (void)data; (void)output; (void)x; (void)y; (void)pw; (void)ph;
    (void)subpixel; (void)make; (void)model; (void)transform;
}

static void wl_output_mode_cb(void *data, struct wl_output *output,
                              uint32_t flags, int32_t width,
                              int32_t height, int32_t refresh) {
    (void)data; (void)output; (void)flags; (void)width; (void)height;
    (void)refresh;
}

static void wl_output_done_cb(void *data, struct wl_output *output) {
    (void)data;
    (void)output;
}

static void wl_output_scale_cb(void *data, struct wl_output *output,
                               int32_t factor) {
    (void)data; (void)output; (void)factor;
}

static void wl_output_description_cb(void *data, struct wl_output *output,
                                     const char *description) {
    (void)data; (void)output; (void)description;
}

static const struct wl_output_listener g_wl_output_listener = {
    .geometry = wl_output_geometry_cb,
    .mode = wl_output_mode_cb,
    .done = wl_output_done_cb,
    .scale = wl_output_scale_cb,
    .name = wl_output_name_cb,
    .description = wl_output_description_cb,
};

static void wl_registry_global(void *data, struct wl_registry *registry,
                               uint32_t name, const char *interface,
                               uint32_t version) {
    wl_shell_state *st = data;
    if (strcmp(interface, zwlr_layer_shell_v1_interface.name) == 0) {
        uint32_t v = version < 4 ? version : 4;
        st->shell = wl_registry_bind(
            registry, name, &zwlr_layer_shell_v1_interface, v);
    } else if (strcmp(interface, wl_compositor_interface.name) == 0) {
        st->compositor = wl_registry_bind(
            registry, name, &wl_compositor_interface,
            version < 4 ? version : 4);
    } else if (strcmp(interface, wl_output_interface.name) == 0) {
        if (st->output_count == st->output_capacity) {
            size_t cap = st->output_capacity ? st->output_capacity * 2 : 4;
            wl_output_rec *grown =
                realloc(st->outputs, cap * sizeof(*grown));
            if (grown == NULL) {
                return; /* OOM: this output is not enumerated */
            }
            st->outputs = grown;
            st->output_capacity = cap;
        }
        wl_output_rec *rec = &st->outputs[st->output_count];
        memset(rec, 0, sizeof(*rec));
        rec->global_name = name;
        rec->output = wl_registry_bind(registry, name,
                                       &wl_output_interface,
                                       version < 4 ? version : 4);
        if (rec->output != NULL) {
            wl_output_add_listener(rec->output, &g_wl_output_listener, rec);
            st->output_count++;
        }
    }
}

static void wl_registry_global_remove(void *data,
                                      struct wl_registry *registry,
                                      uint32_t name) {
    (void)registry;
    wl_shell_state *st = data;
    for (size_t i = 0; i < st->output_count; i++) {
        if (st->outputs[i].global_name == name) {
            st->outputs[i].gone = 1; /* records stay (index stability);
                                      * the proxy is released at
                                      * shutdown */
            return;
        }
    }
}

static const struct wl_registry_listener g_wl_registry_listener = {
    .global = wl_registry_global,
    .global_remove = wl_registry_global_remove,
};

/* Binds the shell's own registry and collects the globals it needs
 * (one roundtrip — the events fan out per-listener, FDK's registry
 * is never touched). Returns 0 when zwlr_layer_shell was offered. */
static int wl_discover(fdk_shell *shell) {
    wl_shell_state *st = shell->wl;
    st->registry = wl_display_get_registry(st->display);
    if (st->registry == NULL) {
        return 0;
    }
    wl_registry_add_listener(st->registry, &g_wl_registry_listener, st);
    if (wl_display_roundtrip(st->display) < 0) {
        return 0;
    }
    return st->shell != NULL && st->compositor != NULL;
}

/* ---- the zwlr_layer_surface_v1 listeners -----------------------------------
 *
 * configure: ack the protocol event, then report the assigned size
 * INTO FDK (notify_configure) — which resizes the render machinery
 * and delivers FDK_EVENT_WINDOW_CONFIGURE to the layer callback.
 * closed: the environment is taking the surface away (an output
 * going gone, most commonly) — deliver the close request; the
 * application responds by destroying the layer. */

static void layer_configure(void *data, struct zwlr_layer_surface_v1 *ls,
                            uint32_t serial, uint32_t width,
                            uint32_t height) {
    (void)ls;
    fdk_shell_layer *layer = data;
    wl_layer_state *lst = layer->backend;
    if (lst == NULL || lst->closed) {
        return;
    }
    zwlr_layer_surface_v1_ack_configure(lst->ls, serial);
    /* The protocol carries the geometry as unsigned; FDK's surface
     * geometry is signed. A compositor assigning more than INT32_MAX
     * pixels is not a real scenario, but the clamp keeps every
     * conversion honest under -Wsign-conversion. */
    if (width > 0 && height > 0 &&
        width <= (uint32_t)INT32_MAX && height <= (uint32_t)INT32_MAX) {
        layer->size.width = (fdk_i32)width;
        layer->size.height = (fdk_i32)height;
        (void)fdk_ext_surface_notify_configure(layer->ext,
                                               (fdk_i32)width,
                                               (fdk_i32)height);
    }
}

static void layer_closed(void *data, struct zwlr_layer_surface_v1 *ls) {
    (void)ls;
    fdk_shell_layer *layer = data;
    wl_layer_state *lst = layer->backend;
    if (lst == NULL) {
        return;
    }
    lst->closed = 1;
    /* The same shape FDK's own toplevel-close handler delivers: the
     * application decides (and destroys the layer). */
    if (layer->cb != NULL) {
        fdk_event_data event;
        memset(&event, 0, sizeof(event));
        event.type = FDK_EVENT_WINDOW_CLOSE_REQUEST;
        layer->cb(layer, &event, layer->cb_user);
    }
}

static const struct zwlr_layer_surface_v1_listener g_layer_listener = {
    .configure = layer_configure,
    .closed = layer_closed,
};

/* ---- the backend contract --------------------------------------------------- */

int fdkshell__wl_probe_global(struct wl_display *display);

int fdkshell__wl_supported(fdk_context *ctx) {
    if (fdk_ext_active_backend(ctx) != FDK_EXT_BACKEND_WAYLAND) {
        return 0;
    }
    fdk_ext_native_display nd;
    if (!fdk_ok(fdk_ext_get_native_display(ctx, &nd)) ||
        nd.display == NULL) {
        return 0;
    }
    /* The probe binds NOTHING (a throwaway registry, one roundtrip,
     * destroyed again) — the real binding happens at init. */
    return fdkshell__wl_probe_global((struct wl_display *)nd.display);
}

/* The support probe's listener state (single-threaded, one probe at
 * a time — the same discipline as fdkshell__pending_layer). */
static int g_probe_found_layer_shell = 0;
static int g_probe_found_compositor = 0;

static void probe_global(void *data, struct wl_registry *registry,
                         uint32_t name, const char *interface,
                         uint32_t version) {
    (void)data;
    (void)registry;
    (void)name;
    (void)version;
    if (strcmp(interface, zwlr_layer_shell_v1_interface.name) == 0) {
        g_probe_found_layer_shell = 1;
    } else if (strcmp(interface, wl_compositor_interface.name) == 0) {
        g_probe_found_compositor = 1;
    }
}

static void probe_global_remove(void *data, struct wl_registry *registry,
                                uint32_t name) {
    (void)data;
    (void)registry;
    (void)name;
}

static const struct wl_registry_listener g_probe_registry_listener = {
    .global = probe_global,
    .global_remove = probe_global_remove,
};

int fdkshell__wl_probe_global(struct wl_display *display) {
    g_probe_found_layer_shell = 0;
    g_probe_found_compositor = 0;
    struct wl_registry *registry = wl_display_get_registry(display);
    if (registry == NULL) {
        return 0;
    }
    wl_registry_add_listener(registry, &g_probe_registry_listener, NULL);
    if (wl_display_roundtrip(display) < 0) {
        wl_registry_destroy(registry);
        return 0;
    }
    wl_registry_destroy(registry);
    return g_probe_found_layer_shell && g_probe_found_compositor;
}

fdk_result fdkshell__wl_init(fdk_shell *shell) {
    wl_shell_state *st = calloc(1, sizeof(*st));
    if (st == NULL) {
        return FDK_ERR_OUT_OF_MEMORY;
    }
    fdk_ext_native_display nd;
    if (!fdk_ok(fdk_ext_get_native_display(shell->ctx, &nd)) ||
        nd.display == NULL) {
        free(st);
        return FDK_ERR_NOT_INITIALIZED;
    }
    st->display = (struct wl_display *)nd.display;
    shell->wl = st;

    if (!wl_discover(shell)) {
        fdkshell__wl_shutdown(shell);
        return FDK_ERR_UNSUPPORTED;
    }
    return FDK_OK;
}

void fdkshell__wl_shutdown(fdk_shell *shell) {
    wl_shell_state *st = shell->wl;
    if (st == NULL) {
        return;
    }
    for (size_t i = 0; i < st->output_count; i++) {
        if (st->outputs[i].output != NULL) {
            wl_output_destroy(st->outputs[i].output);
        }
    }
    free(st->outputs);
    if (st->shell != NULL) {
        zwlr_layer_shell_v1_destroy(st->shell);
    }
    if (st->compositor != NULL) {
        wl_compositor_destroy(st->compositor);
    }
    if (st->registry != NULL) {
        wl_registry_destroy(st->registry);
    }
    free(st);
    shell->wl = NULL;
}

uint32_t fdkshell__wl_output_count(fdk_shell *shell) {
    wl_shell_state *st = shell->wl;
    if (st == NULL) {
        return 0;
    }
    uint32_t n = 0;
    for (size_t i = 0; i < st->output_count; i++) {
        if (!st->outputs[i].gone) {
            n++;
        }
    }
    return n;
}

fdk_result fdkshell__wl_output_name(fdk_shell *shell, uint32_t index,
                                     char *buf, size_t buflen) {
    wl_shell_state *st = shell->wl;
    if (st == NULL) {
        return FDK_ERR_UNSUPPORTED;
    }
    uint32_t live = 0;
    for (size_t i = 0; i < st->output_count; i++) {
        if (st->outputs[i].gone) {
            continue;
        }
        if (live == index) {
            const char *name = st->outputs[i].name;
            snprintf(buf, buflen, "%s",
                     name[0] != '\0' ? name : "output");
            return FDK_OK;
        }
        live++;
    }
    return FDK_ERR_NOT_FOUND;
}

fdk_result fdkshell__wl_layer_create(fdk_shell *shell,
                                      fdk_shell_layer *layer,
                                      fdk_ext_native_handle *out) {
    wl_shell_state *st = shell->wl;
    const fdk_shell_layer_desc *desc = &layer->desc;

    if (st == NULL || st->shell == NULL || st->compositor == NULL) {
        return FDK_ERR_UNSUPPORTED;
    }

    /* Per-output selection (index into the LIVE outputs; -1 passes
     * NULL — the "every output" protocol shape). */
    struct wl_output *output = NULL;
    if (desc->output_index >= 0) {
        uint32_t live = 0;
        int found = 0;
        for (size_t i = 0; i < st->output_count; i++) {
            if (st->outputs[i].gone) {
                continue;
            }
            if ((int32_t)live == desc->output_index) {
                output = st->outputs[i].output;
                found = 1;
                break;
            }
            live++;
        }
        if (!found) {
            return FDK_ERR_NOT_FOUND;
        }
    }

    /* The native surface + its role. */
    struct wl_surface *surface =
        wl_compositor_create_surface(st->compositor);
    if (surface == NULL) {
        return FDK_ERR_WINDOW_CREATE;
    }

    static const uint32_t layer_ids[] = {
        [FDK_SHELL_LAYER_BACKGROUND] = ZWLR_LAYER_SHELL_V1_LAYER_BACKGROUND,
        [FDK_SHELL_LAYER_BOTTOM] = ZWLR_LAYER_SHELL_V1_LAYER_BOTTOM,
        [FDK_SHELL_LAYER_TOP] = ZWLR_LAYER_SHELL_V1_LAYER_TOP,
        [FDK_SHELL_LAYER_OVERLAY] = ZWLR_LAYER_SHELL_V1_LAYER_OVERLAY,
    };

    wl_layer_state *lst = calloc(1, sizeof(*lst));
    if (lst == NULL) {
        wl_surface_destroy(surface);
        return FDK_ERR_OUT_OF_MEMORY;
    }
    lst->output = output;
    lst->closed = 0;
    lst->ls = zwlr_layer_shell_v1_get_layer_surface(
        st->shell, surface, output, layer_ids[desc->layer], "fdk-shell");
    if (lst->ls == NULL) {
        free(lst);
        wl_surface_destroy(surface);
        return FDK_ERR_WINDOW_CREATE;
    }

    /* The desc, 1:1 onto the protocol requests. */
    uint32_t anchor = 0;
    if (desc->anchors & FDK_SHELL_ANCHOR_TOP) {
        anchor |= ZWLR_LAYER_SURFACE_V1_ANCHOR_TOP;
    }
    if (desc->anchors & FDK_SHELL_ANCHOR_BOTTOM) {
        anchor |= ZWLR_LAYER_SURFACE_V1_ANCHOR_BOTTOM;
    }
    if (desc->anchors & FDK_SHELL_ANCHOR_LEFT) {
        anchor |= ZWLR_LAYER_SURFACE_V1_ANCHOR_LEFT;
    }
    if (desc->anchors & FDK_SHELL_ANCHOR_RIGHT) {
        anchor |= ZWLR_LAYER_SURFACE_V1_ANCHOR_RIGHT;
    }
    zwlr_layer_surface_v1_set_anchor(lst->ls, anchor);
    zwlr_layer_surface_v1_set_margin(lst->ls, desc->margin_top,
                                     desc->margin_right,
                                     desc->margin_bottom,
                                     desc->margin_left);
    zwlr_layer_surface_v1_set_exclusive_zone(lst->ls,
                                             desc->exclusive_zone);

    static const uint32_t kbd_modes[] = {
        [FDK_SHELL_KBD_NONE] =
            ZWLR_LAYER_SURFACE_V1_KEYBOARD_INTERACTIVITY_NONE,
        [FDK_SHELL_KBD_EXCLUSIVE] =
            ZWLR_LAYER_SURFACE_V1_KEYBOARD_INTERACTIVITY_EXCLUSIVE,
        [FDK_SHELL_KBD_ON_DEMAND] =
            ZWLR_LAYER_SURFACE_V1_KEYBOARD_INTERACTIVITY_ON_DEMAND,
    };
    uint32_t kbd = kbd_modes[FDK_SHELL_KBD_NONE];
    if (desc->keyboard == FDK_SHELL_KBD_EXCLUSIVE ||
        desc->keyboard == FDK_SHELL_KBD_ON_DEMAND) {
        kbd = kbd_modes[desc->keyboard];
    }
    /* on_demand needs protocol v4; older compositors get the honest
     * downgrade to none (logged once). */
    if (desc->keyboard == FDK_SHELL_KBD_ON_DEMAND &&
        zwlr_layer_surface_v1_get_version(lst->ls) <
            ZWLR_LAYER_SURFACE_V1_KEYBOARD_INTERACTIVITY_ON_DEMAND_SINCE_VERSION) {
        FDKS_WARN("compositor's layer-shell predates v4 — on-demand "
                  "keyboard degrades to none");
        kbd = kbd_modes[FDK_SHELL_KBD_NONE];
    }
    zwlr_layer_surface_v1_set_keyboard_interactivity(lst->ls, kbd);

    /* Size: 0 (compositor assigns) ONLY on opposite-anchored axes —
     * the protocol's rule; other axes carry the desired size
     * (clamped to >= 1: a 0 without opposite anchors is a protocol
     * error). */
    int horiz_anchored = (desc->anchors & FDK_SHELL_ANCHOR_LEFT) &&
                         (desc->anchors & FDK_SHELL_ANCHOR_RIGHT);
    int vert_anchored = (desc->anchors & FDK_SHELL_ANCHOR_TOP) &&
                        (desc->anchors & FDK_SHELL_ANCHOR_BOTTOM);
    int32_t w = horiz_anchored ? 0 : (desc->width > 0 ? desc->width : 1);
    int32_t h = vert_anchored ? 0 : (desc->height > 0 ? desc->height : 1);
    zwlr_layer_surface_v1_set_size(lst->ls, (uint32_t)w, (uint32_t)h);

    zwlr_layer_surface_v1_add_listener(lst->ls, &g_layer_listener, layer);

    layer->backend = lst;
    out->backend = FDK_EXT_BACKEND_WAYLAND;
    out->pointer = surface;
    return FDK_OK;
}

void fdkshell__wl_layer_destroy(fdk_shell *shell,
                                 fdk_shell_layer *layer) {
    (void)shell;
    wl_layer_state *lst = layer->backend;
    if (lst == NULL) {
        return;
    }
    /* Role teardown: the zwlr_layer_surface_v1 object goes first
     * (against the still-live wl_surface — FDK destroys that next).
     * Detach the listener so a configure racing the teardown cannot
     * reach the dying layer through it. */
    if (lst->ls != NULL) {
        /* libwayland offers no listener removal; the guard is the
         * layer's backend pointer, which is NULLed HERE — after
         * this, the listener bodies no-op. */
        zwlr_layer_surface_v1_destroy(lst->ls);
    }
    layer->backend = NULL;
    free(lst);
}

void fdkshell__wl_layer_show(fdk_shell_layer *layer) {
    /* THE handshake starter: an empty wl_surface_commit carries the
     * layer state (anchor, margins, zone, size — all double-buffered
     * per the protocol) and asks the compositor to configure us.
     * Without it no configure ever arrives (the test rig caught
     * exactly that); with a buffer it would be the protocol error
     * layer-shell forbids pre-configure — an EMPTY commit is the
     * sanctioned trigger, the same shape FDK's xdg show() uses. */
    if (layer == NULL || layer->ext == NULL) {
        return;
    }
    fdk_ext_native_handle nh;
    if (!fdk_ok(fdk_ext_surface_native(layer->ext, &nh)) ||
        nh.pointer == NULL) {
        return;
    }
    wl_surface_commit((struct wl_surface *)nh.pointer);
}

void fdkshell__wl_layer_hide(fdk_shell_layer *layer) {
    (void)layer;
    /* Symmetric no-op: a layer surface unmaps by destroying and
     * re-creating its role (documented in fdk-shell.h). */
}

/* ---- the kind's popup_attached hook ---------------------------------------- */

void shell_kind_popup_attached(fdk_ext_surface *surface,
                               void *native_popup, void *user) {
    fdk_shell *shell = user;
    (void)surface;
    /* Find the layer whose ext surface got the popup (the parent
     * hook arrives on the PARENT's surface). */
    fdk_shell_layer *layer = shell->layers_head;
    while (layer != NULL) {
        if (layer->ext == surface) {
            break;
        }
        layer = layer->next;
    }
    if (layer == NULL || layer->backend == NULL) {
        return;
    }
    wl_layer_state *lst = layer->backend;
    if (lst->ls != NULL && native_popup != NULL) {
        /* THE request: parent the xdg_popup to the layer surface —
         * after this the compositor positions the popup relative to
         * the layer and the grab's dismissal semantics apply. */
        zwlr_layer_surface_v1_get_popup(
            lst->ls, (struct xdg_popup *)native_popup);
    }
}

