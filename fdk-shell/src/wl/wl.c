/*
 * wl.c — fdk-shell's Wayland backend (0.1.0)
 *
 * wlr-layer-shell v4 spoken directly on FDK's wl_display, through
 * the extension API's documented accessors — the reference shape
 * for every "add-on speaks its own protocol" package:
 *
 *   - fdk_ext_get_native_display() yields the wl_display*;
 *   - this file binds its OWN wl_registry (a second registry is
 *     ordinary Wayland: each registry's events fan out to its own
 *     listener, FDK's registry is untouched), discovers
 *     zwlr_layer_shell_v1 and the outputs, and rounds the discovery
 *     trip;
 *   - each layer's wl_surface is created from the compositor global
 *     and given the zwlr_layer_surface_v1 role with the desc's
 *     parameters; FDK then adopts the surface (event routing, the
 *     fdk_surface render path, popup parenting);
 *   - the role's configure callback acks the protocol event and
 *     reports the assigned size through
 *     fdk_ext_surface_notify_configure() — FDK resizes its render
 *     machinery and delivers FDK_EVENT_WINDOW_CONFIGURE to the
 *     layer's callback;
 *   - popups parent through the kind's popup_attached hook (the
 *     zwlr_layer_surface_v1.get_popup request — the waybar pattern).
 *
 * The bindings are generated by wayland-scanner from the vendored
 * wlr-protocols XML (src/wl/protocol/) — the same generation FDK
 * itself uses for xdg-shell, run from this package's own Makefile.
 */

#include "shell_internal.h"

